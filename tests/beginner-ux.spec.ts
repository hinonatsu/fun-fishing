import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {decodeBuild,encodeBuild} from '../src/domain';
import {completedBuild,noOverflow} from './helpers';

test('editing conditions preserves the plan, and an unsuitable M can use another preparation method',async({page})=>{
  const build=completedBuild();
  build.preparation={tripDate:'2026-10-30'};
  await page.goto(`./?build=${encodeBuild(build)}#builder`);
  await page.getByRole('button',{name:'10月 変更（釣行月）',exact:true}).click();
  await page.getByRole('button',{name:/^11月/}).click();
  await expect(page).toHaveURL(/#builder$/);
  await expect(page.locator('tr[data-category="rod"]')).toContainText('3-300');
  await page.getByRole('button',{name:'安全用品を変更する',exact:true}).click();
  await page.getByLabel('身長（cm・任意）',{exact:true}).fill('185');
  await page.getByLabel('胸囲（cm・任意）',{exact:true}).fill('105');
  await expect(page.getByRole('button',{name:'この商品を選ぶ：トカラウ BSJ-201ARS レッド M',exact:true})).toBeDisabled();
  await page.getByText('掲載商品以外の準備方法を選ぶ',{exact:true}).click();
  await page.getByRole('button',{name:'施設の貸出を確認して用意する',exact:true}).click();
  await expect(page).toHaveURL(/#builder$/);
  await expect(page.locator('tr[data-category="safety"]')).toContainText('準備先を選択');
  await expect(page.getByLabel('今回の購入費用')).toContainText('費用は別途未確定');
  const saved=decodeBuild(await page.evaluate(()=>localStorage.getItem('fun-fishing-build-v1')!))!;
  expect(saved.preparation?.tripDate).toBeUndefined();
  expect(saved.preparation?.arrangements?.safety).toBe('rental');
  expect(JSON.stringify(saved)).not.toContain('185');
  await noOverflow(page);
});

test('partial prices, optional removal, quantities, shipping, preparation and sharing remain consistent',async({page,context})=>{
  test.setTimeout(120_000);
  await page.route('**/src/data/amazon-prices.json*',r=>r.fulfill({contentType:'application/javascript',body:'export default {schemaVersion:1,updatedAt:null,products:{}};'}));
  const build=completedBuild();
  build.answers.budget='20000';
  build.prices=Object.fromEntries(Object.values(build.selection).filter(Boolean).map(id=>[id,3000]));
  delete build.prices[build.selection.rod];
  await page.goto(`./?build=${encodeBuild(build)}#builder`);
  const cost=page.getByLabel('今回の購入費用');
  await expect(cost).toContainText('確認済み分 21,000円');
  await expect(cost).toContainText('1,000円超過');
  await page.getByRole('button',{name:'バケツは今回は買わない',exact:true}).click();
  await expect(cost).toContainText('確認済み分 18,000円');
  await expect(cost).toContainText('一式の予算判定は未確定');
  await page.getByRole('button',{name:'元に戻す',exact:true}).click();
  await page.getByRole('button',{name:'価格をまとめて確認・入力',exact:true}).click();
  await page.getByRole('spinbutton',{name:'リバティクラブ 小継 磯 3-300の税込価格',exact:true}).fill('1000');
  await expect(page.getByText('比較商品の税込価格（円）',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'価格を保存して戻る',exact:true}).click();
  await page.getByRole('spinbutton',{name:'バケツの購入数',exact:true}).fill('2');
  await expect(cost).toContainText('25,000円');
  await page.getByRole('button',{name:'選んだ道具を確認する',exact:true}).click();
  await expect(page.locator('.review-compatibility').first()).toHaveAttribute('open','');
  await page.getByRole('button',{name:'購入先ごとの送料を確認',exact:true}).click();
  await page.getByRole('spinbutton',{name:'注文1の送料',exact:true}).fill('600');
  await page.getByRole('button',{name:'送料を保存して戻る',exact:true}).click();
  await expect(cost).toContainText('25,600円');
  await page.getByRole('button',{name:'購入先の確認・リストの保存へ',exact:true}).click();
  await page.getByRole('button',{name:/購入先と当日の持ち物を確認する/}).click();
  await page.getByRole('checkbox',{name:/タオル/}).check();
  await page.getByRole('button',{name:'このチェックリストを保管・共有',exact:true}).click();
  await expect(page.getByRole('img',{name:'この買い物リストを開くQRコード',exact:true})).toBeVisible();
  await page.getByText('リンクの文字列を表示・手動コピー',{exact:true}).click();
  const url=await page.getByLabel('この買い物リストを開くリンク',{exact:true}).inputValue();
  const shared=await context.newPage();await shared.goto(url);
  await expect(shared.getByRole('checkbox',{name:/タオル/})).toBeChecked();
  await expect(shared.getByRole('spinbutton',{name:'バケツの購入数',exact:true})).toHaveValue('2');
  await shared.close();
  await page.getByRole('button',{name:'買い物リストに戻る',exact:true}).click();
  await expect(page).toHaveURL(/#list$/);
  await noOverflow(page);
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
});
